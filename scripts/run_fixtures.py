"""Run every fixture photo through the full pipeline.

- records a PANIC take per fixture (takes/<fixture_id>/)
- writes bench/results/fixtures.md (per-fixture before/after, timings) for the README
Usage: backend/.venv/Scripts/python scripts/run_fixtures.py [fixture_id ...]
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from traceless.pipeline import Session  # noqa: E402
from traceless.schemas import Truth  # noqa: E402


def km(v):
    return "—" if v is None else (f"{v:,.0f} km" if v >= 10 else f"{v:.1f} km")


def main(ids: list[str]) -> None:
    man = json.loads((ROOT / "fixtures" / "manifest.json").read_text(encoding="utf-8"))
    rows = []
    for fx in man:
        if ids and fx["id"] not in ids:
            continue
        truth = Truth(lat=fx["lat"], lon=fx["lon"], source="fixture", public_landmark=fx.get("public_landmark", False))
        s = Session((ROOT / "fixtures" / fx["file"]).read_bytes(), fx["file"], truth=truth, source="sim", fixture_id=fx["id"])
        t0 = time.time()
        s.run()
        st = s.snapshot()
        if st["stage"] != "done":
            rows.append(f"| {fx['id']} | error: {st.get('error')} |||||||")
            continue
        s.save_take(fx["id"])
        b = {a["attacker_id"]: a for a in st["attacks"]}
        g = b["geoclip"]
        if st["already_safe"]:
            after, verdict, q = "already hard to place", "—", None
        else:
            last = st["defense"]["rounds"][-1]
            ga = next(a for a in last["attacks"] if a["attacker_id"] == "geoclip")
            ad = next((a for a in last["attacks"] if a["attacker_id"] == "geoclip-adaptive"), None)
            after = f"{km(ga['distance_km'])} / adaptive {km(ad and ad['distance_km'])}"
            verdict = "✅ reached" if st["defense"]["reached_target"] else "⚠️ not reached"
            q = last["quality"]
        t = st["timings"]
        rows.append(
            f"| {fx['id']} | {fx['category']} | {km(g['distance_km'])} | {after} | {verdict} | "
            f"{'—' if q is None else f'{q['pct_pixels_changed']:.1f}% / {q['ssim']:.3f}'} | "
            f"{t.get('attack', 0):.1f}s / {t.get('ablation', 0):.1f}s / {t.get('defense', 0):.1f}s |"
        )
        print(rows[-1], f"({time.time() - t0:.0f}s)", flush=True)
        s.delete()
    import torch

    dev = torch.cuda.get_device_name(0) if torch.cuda.is_available() else "CPU"
    md = [
        f"_Generated by `scripts/run_fixtures.py` on {time.strftime('%Y-%m-%d')} ({dev}), offline attackers only, radius 25 km._",
        "",
        "| fixture | type | GeoCLIP before | GeoCLIP after / adaptive | 25 km target | pixels changed / SSIM | attack / ablation / defense time |",
        "|---|---|---|---|---|---|---|",
        *rows,
    ]
    out = ROOT / "bench" / "results" / "fixtures.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    if not ids:
        out.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main(sys.argv[1:])
